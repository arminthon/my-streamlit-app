import streamlit as st
import pandas as pd

st.title("داشبورد مدیریتی آرمین 🚀")
st.write("این اپلیکیشن با پایتون و Streamlit ساخته شده است.")

# دیتای تستی
data = {
    'دپارتمان': ['HSE', 'IT', 'Finance', 'HR'],
    'تعداد کارمندان': [5, 12, 8, 4],
    'میانگین حقوق': [50, 75, 60, 45]  # به هزار دلار یا واحد دلخواه
}
df = pd.DataFrame(data)

# اضافه کردن یک اسلایدر تعاملی برای فیلتر کردن حقوق
st.subheader("⚙️ فیلتر بر اساس حداقل حقوق")
min_salary = st.slider("حداقل حقوق مورد نظر را انتخاب کنید:", 40, 80, 50)

# فیلتر کردن دیتافریم بر اساس مقدار اسلایدر
filtered_df = df[df['میانگین حقوق'] >= min_salary]

# نمایش جدول فیلترشده
st.dataframe(filtered_df)

# نمایش یک نمودار میله‌ای ساده آماده توی استریم‌لیت
st.subheader("📊 نمودار مقایسه حقوق دپارتمان‌ها")
st.bar_chart(filtered_df.set_index('دپارتمان')['میانگین حقوق'])
